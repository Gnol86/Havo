export function resolveLanguage(locale?: string): "en" | "fr" | "es" {
  const language = locale?.trim().toLowerCase().split(/[-_]/)[0];
  return language === "fr" || language === "es" ? language : "en";
}

export function translate(key: TranslationKey, locale?: string): string {
  return { en, fr, es }[resolveLanguage(locale)][key];
}
